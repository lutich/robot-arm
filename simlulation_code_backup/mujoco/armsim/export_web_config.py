"""Writes web/arm3d-config.js from config/robot.yaml, config/scene.yaml and robot-arm's poses.

    python -m armsim.export_web_config

The browser view has no YAML parser and must work without any server, so the numbers are
exported once as a JavaScript module and checked in. A test keeps the export in sync.
"""
import json
from pathlib import Path

from armsim.cameras import fit_oak_camera
from armsim.config import ROOT, load_robot, load_scene
from armsim.robotarm import BOUNDS, HOME, PARK, commit

TARGET = ROOT / 'web' / 'arm3d-config.js'


def web_config(robot=None, scene=None, oak=None):
    robot, scene = robot or load_robot(), scene or load_scene()
    if oak is None:
        try:
            oak = fit_oak_camera(width=scene['render']['width'], height=scene['render']['height'])
        except (OSError, RuntimeError, ValueError, KeyError):
            oak = None
    channels = {str(c): {k: v for k, v in robot['channels'][c].items()} for c in range(6)}
    return dict(
        source='generated by python -m armsim.export_web_config from config/robot.yaml and config/scene.yaml',
        robot_arm_commit=commit(),
        links=robot['links'], gripper=robot['gripper'], servo=robot['servo'], channels=channels,
        bounds={str(c): list(BOUNDS[c]) for c in range(6)},
        home=[HOME[c] for c in range(6)], park=[PARK[c] for c in range(6)],
        table=scene['table'], base=scene['base'], blocks=scene['blocks'], slots=scene['slots'],
        layout=scene['layout'], task=scene['task'], render=scene['render'],
        oak=None if oak is None else dict(pos=oak['pos'], xyaxes=oak['xyaxes'], fovy=oak['fovy']))


def render(config):
    return ('// Generated file, do not edit: python -m armsim.export_web_config\n'
            'export const CONFIG = ' + json.dumps(config, indent=2, sort_keys=True) + ';\n')


def main():
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(render(web_config()))
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
